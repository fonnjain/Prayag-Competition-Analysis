/**
 * Post-codegen patch: orval always emits `export * from './generated/types'`
 * in lib/api-zod/src/index.ts even when the schemas option is absent.
 * Since generated/types no longer exists, that line causes TS2307.
 * This script overwrites index.ts with only the zod-schema re-export.
 * The actual package entry point is main.ts (manually maintained).
 */
import { writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const indexPath = resolve(__dirname, "../api-zod/src/index.ts");

writeFileSync(
  indexPath,
  `// Generated by orval – patched by patch-zod-index.mjs to remove stale re-exports.
// Do not edit: re-run \`pnpm --filter @workspace/api-spec run codegen\` to regenerate.
export * from "./generated/api";
`,
);

console.log("✅ Patched lib/api-zod/src/index.ts");
