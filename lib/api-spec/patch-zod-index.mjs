/**
 * Post-codegen patch: orval always emits `export * from './generated/types'`
 * in lib/api-zod/src/index.ts even when the schemas option is absent.
 * Since generated/types no longer exists, that line causes TS2307.
 * This script overwrites index.ts with only the zod-schema re-export.
 *
 * It also regenerates generated/types/index.ts to only barrel-export the
 * type files that orval actually wrote in that run, preventing TS2307 from
 * stale exports that referenced deleted files.
 *
 * The actual package entry point is main.ts (manually maintained).
 */
import { writeFileSync, readdirSync, mkdirSync } from "fs";
import { resolve, dirname, basename } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

// 1. Fix lib/api-zod/src/index.ts
const indexPath = resolve(root, "api-zod/src/index.ts");
writeFileSync(
  indexPath,
  `// Generated by orval – patched by patch-zod-index.mjs to remove stale re-exports.
// Do not edit: re-run \`pnpm --filter @workspace/api-spec run codegen\` to regenerate.
export * from "./generated/api";
`,
);
console.log("✅ Patched lib/api-zod/src/index.ts");

// 2. Regenerate lib/api-zod/src/generated/types/index.ts from actual files on disk.
//    orval's clean:true only cleans the files it manages (the target dir). Because
//    the `schemas` option was removed, orval no longer manages generated/types/.
//    Stale type files from older runs may remain and cause TS2307 errors when they
//    import deleted sibling modules. We scan for broken imports and delete stale
//    files, then rebuild the barrel from what remains.
import { readFileSync, unlinkSync } from "fs";
const typesDir = resolve(root, "api-zod/src/generated/types");
const typesIndexPath = resolve(typesDir, "index.ts");
mkdirSync(typesDir, { recursive: true });

let allTypeFiles = [];
try {
  allTypeFiles = readdirSync(typesDir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .sort();
} catch {
  // types/ directory doesn't exist — nothing to barrel
}

// Delete any type file whose local imports (e.g. `from './foo'`) reference a
// sibling module that doesn't exist on disk. These are stale from a previous
// orval run that generated more files than the current config does.
const existingNames = new Set(allTypeFiles.map((f) => basename(f, ".ts")));
const staleFiles = [];
for (const f of allTypeFiles) {
  const content = readFileSync(resolve(typesDir, f), "utf8");
  const localImports = [...content.matchAll(/from ['"]\.\/([^'"]+)['"]/g)].map(
    (m) => m[1],
  );
  const hasBrokenImport = localImports.some((imp) => !existingNames.has(imp));
  if (hasBrokenImport) {
    staleFiles.push(f);
  }
}
// Also expand: if a file depends on a stale file, it becomes stale too.
// One pass is enough for typical single-level deps in generated types.
const staleNames = new Set(staleFiles.map((f) => basename(f, ".ts")));
for (const f of allTypeFiles) {
  if (staleNames.has(basename(f, ".ts"))) continue;
  const content = readFileSync(resolve(typesDir, f), "utf8");
  const localImports = [...content.matchAll(/from ['"]\.\/([^'"]+)['"]/g)].map(
    (m) => m[1],
  );
  if (localImports.some((imp) => staleNames.has(imp))) {
    staleFiles.push(f);
    staleNames.add(basename(f, ".ts"));
  }
}

for (const f of staleFiles) {
  unlinkSync(resolve(typesDir, f));
  console.log(`🗑️  Deleted stale type file: generated/types/${f}`);
}

let typeFiles = [];
try {
  typeFiles = readdirSync(typesDir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .sort();
} catch {
  // types/ directory doesn't exist — nothing to barrel
}

const banner = `/**
 * Generated by orval v8.9.1 🍺
 * Barrel patched by patch-zod-index.mjs — only exports types that exist on disk.
 * Do not edit manually.
 */
`;
const exports = typeFiles
  .map((f) => `export * from './${basename(f, ".ts")}';`)
  .join("\n");

writeFileSync(typesIndexPath, banner + (exports ? exports + "\n" : ""));
console.log(
  `✅ Patched lib/api-zod/src/generated/types/index.ts (${typeFiles.length} type${typeFiles.length === 1 ? "" : "s"})`,
);
